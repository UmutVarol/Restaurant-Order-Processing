// Writes qr-data.js: the QR code of the project's address as an SVG path, made with the app's own QR library.
// video.html runs from file://, where it cannot import the module itself.   node make-qr.mjs [url]
import { writeFileSync } from 'node:fs';
import qrcode from '../../src/main/resources/static/assets/js/vendor/qrcode.mjs';

const url = process.argv[2] || 'https://github.com/UmutVarol/Restaurant-Order-Processing';
const qr = qrcode(0, 'M');
qr.addData(url);
qr.make();
const size = qr.getModuleCount();
let d = '';
for (let row = 0; row < size; row += 1) for (let col = 0; col < size; col += 1) if (qr.isDark(row, col)) d += `M${col} ${row}h1v1h-1z`;
writeFileSync(new URL('./qr-data.js', import.meta.url), `// Generated by make-qr.mjs for ${url}\nwindow.QR = ${JSON.stringify({ url, size, d })};\n`);
console.log(`qr-data.js: ${size}×${size} modules for ${url}`);
