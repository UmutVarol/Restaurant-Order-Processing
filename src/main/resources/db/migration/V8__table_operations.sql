-- Table operations: voiding and comping units of a line, a manual discount on an order, moving and merging tables.

-- quantity stays what was ordered; voided units are taken off, comped units are made but not charged
ALTER TABLE order_lines ADD COLUMN voided_quantity INTEGER NOT NULL DEFAULT 0;
ALTER TABLE order_lines ADD COLUMN comped_quantity INTEGER NOT NULL DEFAULT 0;
ALTER TABLE order_lines ADD CONSTRAINT ck_order_lines_adjusted
    CHECK (voided_quantity >= 0 AND comped_quantity >= 0 AND voided_quantity + comped_quantity <= quantity);

-- a manual discount is either a percentage or a fixed amount, on top of any coupon
ALTER TABLE orders ADD COLUMN manual_discount_percent NUMERIC(5, 2);
ALTER TABLE orders ADD COLUMN manual_discount_amount NUMERIC(12, 2);
ALTER TABLE orders ADD CONSTRAINT ck_orders_manual_discount
    CHECK ((manual_discount_percent IS NULL OR (manual_discount_percent > 0 AND manual_discount_percent <= 100))
        AND (manual_discount_amount IS NULL OR manual_discount_amount > 0)
        AND (manual_discount_percent IS NULL OR manual_discount_amount IS NULL));

-- every void, comp, discount, move and merge, with who asked and which manager approved it
CREATE TABLE order_adjustments
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT                   NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    line_id     BIGINT,
    kind        VARCHAR(20)              NOT NULL,
    item_name   VARCHAR(80),
    quantity    INTEGER,
    amount      NUMERIC(12, 2),
    detail      VARCHAR(255),
    actor       VARCHAR(50)              NOT NULL,
    approved_by VARCHAR(50),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_order_adjustments_kind CHECK (kind IN ('VOID', 'COMP', 'DISCOUNT', 'MOVE', 'MERGE'))
);

CREATE INDEX ix_order_adjustments_order_id ON order_adjustments (order_id);
