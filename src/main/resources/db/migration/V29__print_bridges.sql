-- Print bridges (docs/PRINT_BRIDGE.md): a small program in the restaurant fetches its branch's kitchen tickets from
-- Sofra and sends them to the printers on the local network. Needed wherever the server cannot reach the printers
-- itself, which is always the case for Sofra Cloud.
ALTER TABLE printers ADD COLUMN via_bridge BOOLEAN DEFAULT FALSE NOT NULL;

CREATE TABLE print_bridges
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT                   NOT NULL REFERENCES businesses (id),
    branch_id    BIGINT                   NOT NULL REFERENCES branches (id),
    name         VARCHAR(60)              NOT NULL,
    token_hash   VARCHAR(64)              NOT NULL UNIQUE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by   VARCHAR(50)              NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE,
    revoked_at   TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_print_bridges_business ON print_bridges (business_id);
