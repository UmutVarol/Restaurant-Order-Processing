-- The Chain plan's central menu with each branch's own price and sales: a row only where a branch differs from the
-- central menu. A null price keeps the central price; a null "available" keeps the central sold-out state.
CREATE TABLE branch_menu_items
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT                   NOT NULL REFERENCES businesses (id),
    branch_id    BIGINT                   NOT NULL REFERENCES branches (id),
    menu_item_id BIGINT                   NOT NULL REFERENCES menu_items (id),
    price        NUMERIC(12, 2),
    available    BOOLEAN,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by   VARCHAR(50)              NOT NULL,
    CONSTRAINT uq_branch_menu_items UNIQUE (branch_id, menu_item_id),
    CONSTRAINT ck_branch_menu_items_price CHECK (price IS NULL OR price > 0)
);
CREATE INDEX ix_branch_menu_items_branch ON branch_menu_items (branch_id);
