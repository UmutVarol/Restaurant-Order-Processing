-- Planning the day: dishes the kitchen marked as prepared for a day (from the forecast), and waste recorded with a
-- structured reason, as a dish's portions or an ingredient, with what it was worth.
CREATE TABLE prep_checks
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT                   NOT NULL REFERENCES businesses (id),
    branch_id    BIGINT                   NOT NULL REFERENCES branches (id),
    prep_date    DATE                     NOT NULL,
    menu_item_id BIGINT                   NOT NULL REFERENCES menu_items (id),
    done_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    done_by      VARCHAR(50)              NOT NULL,
    CONSTRAINT uq_prep_checks UNIQUE (branch_id, prep_date, menu_item_id)
);
CREATE INDEX ix_prep_checks_day ON prep_checks (business_id, prep_date);

CREATE TABLE waste_entries
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id   BIGINT                   NOT NULL REFERENCES businesses (id),
    branch_id     BIGINT                   NOT NULL REFERENCES branches (id),
    menu_item_id  BIGINT REFERENCES menu_items (id),
    ingredient_id BIGINT REFERENCES ingredients (id),
    name          VARCHAR(120)             NOT NULL,
    quantity      NUMERIC(12, 3)           NOT NULL,
    unit          VARCHAR(10)              NOT NULL,
    reason        VARCHAR(15)              NOT NULL,
    note          VARCHAR(200),
    cost          NUMERIC(12, 2)           NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by    VARCHAR(50)              NOT NULL,
    -- the tablet's own id for the entry: sent twice (a double tap, a retry), it is recorded once
    request_key   VARCHAR(64),
    CONSTRAINT uq_waste_entries_request UNIQUE (business_id, request_key),
    CONSTRAINT ck_waste_entries_what CHECK ((menu_item_id IS NULL) <> (ingredient_id IS NULL)),
    CONSTRAINT ck_waste_entries_reason CHECK (reason IN ('EXPIRED', 'SPOILED', 'OVERPRODUCED', 'RETURNED', 'DROPPED', 'OTHER')),
    CONSTRAINT ck_waste_entries_quantity CHECK (quantity > 0)
);
CREATE INDEX ix_waste_entries_time ON waste_entries (business_id, created_at);
