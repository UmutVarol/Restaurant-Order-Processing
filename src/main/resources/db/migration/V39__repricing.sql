-- Inflation tools: prices changed many at a time (a percentage or an amount, rounded), kept as a batch so the change
-- can be looked back on and undone; and the food cost a business aims for, against which dishes are flagged.
CREATE TABLE price_changes
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT                   NOT NULL REFERENCES businesses (id),
    mode        VARCHAR(10)              NOT NULL,
    amount      NUMERIC(12, 2),
    rounding    VARCHAR(10)              NOT NULL,
    item_count  INT                      NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by  VARCHAR(50)              NOT NULL,
    reverted_at TIMESTAMP WITH TIME ZONE,
    reverted_by VARCHAR(50),
    CONSTRAINT ck_price_changes_mode CHECK (mode IN ('PERCENT', 'AMOUNT', 'EXACT'))
);
CREATE INDEX ix_price_changes_created ON price_changes (business_id, created_at);

CREATE TABLE price_change_lines
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT         NOT NULL REFERENCES businesses (id),
    change_id    BIGINT         NOT NULL REFERENCES price_changes (id),
    menu_item_id BIGINT         NOT NULL REFERENCES menu_items (id),
    -- null: the central price; otherwise that branch's own price
    branch_id    BIGINT REFERENCES branches (id),
    old_price    NUMERIC(12, 2) NOT NULL,
    new_price    NUMERIC(12, 2) NOT NULL
);
CREATE INDEX ix_price_change_lines_change ON price_change_lines (change_id);

CREATE TABLE pricing_settings
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id       BIGINT                   NOT NULL REFERENCES businesses (id),
    -- the share of the price before VAT that ingredients may take
    target_food_cost  NUMERIC(5, 2)            NOT NULL DEFAULT 30,
    rounding          VARCHAR(10)              NOT NULL DEFAULT 'ONE',
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by        VARCHAR(50)              NOT NULL,
    CONSTRAINT uq_pricing_settings UNIQUE (business_id),
    CONSTRAINT ck_pricing_settings_target CHECK (target_food_cost > 0 AND target_food_cost < 100)
);
