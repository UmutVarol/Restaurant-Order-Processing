-- Bookings and the walk-in waitlist. Both are a party that will sit at a table: a booking for a time, a walk-in as
-- soon as a table frees up. Phone numbers are personal data and are erased some days after the visit.
CREATE TABLE reservations
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind             VARCHAR(10)              NOT NULL,
    status           VARCHAR(10)              NOT NULL,
    guest_name       VARCHAR(60)              NOT NULL,
    phone            VARCHAR(20),
    party_size       INTEGER                  NOT NULL,
    -- a booking's time; for a walk-in, when they arrived (and, once seated, when they sat down)
    starts_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_minutes INTEGER                  NOT NULL,
    quoted_minutes   INTEGER,
    table_id         BIGINT REFERENCES dining_tables (id),
    note             VARCHAR(140),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by       VARCHAR(50)              NOT NULL,
    seated_at        TIMESTAMP WITH TIME ZONE,
    closed_at        TIMESTAMP WITH TIME ZONE,
    closed_by        VARCHAR(50),
    version          BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT ck_reservations_kind CHECK (kind IN ('BOOKING', 'WALK_IN')),
    CONSTRAINT ck_reservations_status CHECK (status IN ('BOOKED', 'WAITING', 'SEATED', 'FINISHED', 'CANCELLED', 'NO_SHOW')),
    CONSTRAINT ck_reservations_party CHECK (party_size BETWEEN 1 AND 30),
    CONSTRAINT ck_reservations_duration CHECK (duration_minutes BETWEEN 15 AND 360)
);

CREATE INDEX ix_reservations_status_start ON reservations (status, starts_at);
CREATE INDEX ix_reservations_table ON reservations (table_id, status);
