-- Quick staff switching on registered tills: a PIN per staff member, usable only from a registered device.

ALTER TABLE app_users ADD COLUMN pin_hash VARCHAR(100);
-- PIN lockouts in a row; after a few the PIN is cleared and must be set again with the password.
ALTER TABLE app_users ADD COLUMN pin_lockouts INT NOT NULL DEFAULT 0;

CREATE TABLE pos_devices
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(60)              NOT NULL,
    -- SHA-256 of the device token; the token itself is shown once, when the device is registered
    token_hash   VARCHAR(64)              NOT NULL UNIQUE,
    created_by   VARCHAR(50)              NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE,
    revoked_at   TIMESTAMP WITH TIME ZONE
);
