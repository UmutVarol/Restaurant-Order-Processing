ALTER TABLE order_lines ADD COLUMN fired_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE order_lines ADD COLUMN ready_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE order_lines ADD CONSTRAINT ck_order_lines_course CHECK (course BETWEEN 1 AND 3);
UPDATE order_lines SET station_code = CASE category WHEN 'STARTER' THEN 'COLD' WHEN 'MAIN' THEN 'HOT'
    WHEN 'DESSERT' THEN 'DESSERT' ELSE 'BAR' END;
-- everything ordered before courses existed went to the kitchen at once
UPDATE order_lines SET fired_at = (SELECT o.created_at FROM orders o WHERE o.id = order_lines.order_id);

