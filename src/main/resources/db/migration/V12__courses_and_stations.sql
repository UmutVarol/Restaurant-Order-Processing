-- Kitchen stations (where a dish is made) and courses (when it is made).

CREATE TABLE stations
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- stable key used by menu items, order lines and printers
    code           VARCHAR(20) NOT NULL UNIQUE,
    name           VARCHAR(40) NOT NULL UNIQUE,
    -- minutes a fired course may take at this station before the kitchen screen turns it red
    target_minutes INTEGER     NOT NULL,
    sort_order     INTEGER     NOT NULL,
    CONSTRAINT ck_stations_code CHECK (code = UPPER(code)),
    CONSTRAINT ck_stations_target CHECK (target_minutes BETWEEN 1 AND 240)
);

