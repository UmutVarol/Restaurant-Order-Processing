-- Payments: bills, the payments and refunds made against them, guest payment links and end-of-day closings.
-- Portable across PostgreSQL and H2. Existing orders get bills and payments in V4 (a Java migration).

-- A bill is what a guest settles: every order of one dine-in seating, or a single takeaway or delivery order.
CREATE TABLE bills
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 5001) PRIMARY KEY,
    status    VARCHAR(20)              NOT NULL,
    table_id  BIGINT REFERENCES dining_tables (id),
    opened_at TIMESTAMP WITH TIME ZONE NOT NULL,
    closed_at TIMESTAMP WITH TIME ZONE,
    version   BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT ck_bills_status CHECK (status IN ('OPEN', 'CLOSED', 'VOID'))
);

CREATE INDEX ix_bills_table_status ON bills (table_id, status);

-- Each order belongs to exactly one bill.
CREATE TABLE bill_orders
(
    bill_id  BIGINT NOT NULL REFERENCES bills (id),
    order_id BIGINT NOT NULL REFERENCES orders (id),
    PRIMARY KEY (bill_id, order_id),
    CONSTRAINT uq_bill_orders_order UNIQUE (order_id)
);

CREATE TABLE payments
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id             BIGINT                   NOT NULL REFERENCES bills (id),
    method              VARCHAR(20)              NOT NULL,
    status              VARCHAR(20)              NOT NULL,
    amount              NUMERIC(12, 2)           NOT NULL,
    tip                 NUMERIC(12, 2)           NOT NULL DEFAULT 0,
    tendered            NUMERIC(12, 2),
    change_due          NUMERIC(12, 2),
    refunded_amount     NUMERIC(12, 2)           NOT NULL DEFAULT 0,
    provider            VARCHAR(20),
    provider_token      VARCHAR(120),
    provider_payment_id VARCHAR(120),
    approval_code       VARCHAR(20),
    idempotency_key     VARCHAR(80),
    payment_link_id     BIGINT,
    failure_reason      VARCHAR(255),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at        TIMESTAMP WITH TIME ZONE,
    created_by          VARCHAR(50)              NOT NULL,
    version             BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT ck_payments_method CHECK (method IN ('CASH', 'CARD', 'ONLINE')),
    CONSTRAINT ck_payments_status CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'EXPIRED')),
    CONSTRAINT ck_payments_amounts CHECK (amount > 0 AND tip >= 0 AND refunded_amount >= 0 AND refunded_amount <= amount),
    CONSTRAINT ck_payments_cash CHECK (tendered IS NULL OR tendered >= amount + tip),
    CONSTRAINT uq_payments_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT uq_payments_provider_token UNIQUE (provider_token)
);

CREATE INDEX ix_payments_bill ON payments (bill_id);
CREATE INDEX ix_payments_status_created ON payments (status, created_at);

CREATE TABLE refunds
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id         BIGINT                   NOT NULL REFERENCES payments (id),
    amount             NUMERIC(12, 2)           NOT NULL,
    status             VARCHAR(20)              NOT NULL,
    reason             VARCHAR(255)             NOT NULL,
    provider_refund_id VARCHAR(120),
    failure_reason     VARCHAR(255),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by         VARCHAR(50)              NOT NULL,
    CONSTRAINT ck_refunds_amount CHECK (amount > 0),
    CONSTRAINT ck_refunds_status CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED'))
);

CREATE INDEX ix_refunds_payment ON refunds (payment_id);

-- Guest payment links (QR codes). Only a SHA-256 hash of the token is stored, so a database leak does not
-- hand out working links.
CREATE TABLE payment_links
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id    BIGINT                   NOT NULL REFERENCES bills (id),
    token_hash VARCHAR(64)              NOT NULL,
    amount     NUMERIC(12, 2),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked    BOOLEAN                  NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by VARCHAR(50)              NOT NULL,
    CONSTRAINT uq_payment_links_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_payment_links_amount CHECK (amount IS NULL OR amount > 0)
);

ALTER TABLE payments
    ADD CONSTRAINT fk_payments_link FOREIGN KEY (payment_link_id) REFERENCES payment_links (id);

-- End of day: what the drawer should hold against what was counted.
CREATE TABLE day_closings
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_date DATE                     NOT NULL,
    expected_cash NUMERIC(12, 2)           NOT NULL,
    counted_cash  NUMERIC(12, 2)           NOT NULL,
    variance      NUMERIC(12, 2)           NOT NULL,
    card_total    NUMERIC(12, 2)           NOT NULL,
    online_total  NUMERIC(12, 2)           NOT NULL,
    tips_total    NUMERIC(12, 2)           NOT NULL,
    refunds_total NUMERIC(12, 2)           NOT NULL,
    note          VARCHAR(255),
    closed_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    closed_by     VARCHAR(50)              NOT NULL,
    CONSTRAINT uq_day_closings_date UNIQUE (business_date),
    CONSTRAINT ck_day_closings_counted CHECK (counted_cash >= 0)
);
