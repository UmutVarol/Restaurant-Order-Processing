-- e-Adisyon (VUK 509, GİB): a business the Revenue Administration has notified keeps an electronic adisyon for every
-- table it serves. It is opened with the table's first order, follows what is added, and is closed with the legal
-- document (ÖKC receipt or e-Arşiv invoice) of the payment. Each version is sent to the business's own GİB-authorised
-- integrator, retried until it is accepted.
CREATE TABLE adisyons
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id     BIGINT                   NOT NULL REFERENCES businesses (id),
    branch_id       BIGINT                   NOT NULL REFERENCES branches (id),
    bill_id         BIGINT                   NOT NULL REFERENCES bills (id),
    -- the document's universal id (ETTN), fixed for its whole life
    ettn            VARCHAR(36)              NOT NULL,
    table_code      VARCHAR(20),
    status          VARCHAR(10)              NOT NULL,
    total           NUMERIC(12, 2)           NOT NULL,
    tax             NUMERIC(12, 2)           NOT NULL,
    -- "rate:gross:vat" joined by "|", as on orders
    vat_lines       VARCHAR(255),
    item_count      INT                      NOT NULL DEFAULT 0,
    fiscal_number   VARCHAR(40),
    opened_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    closed_at       TIMESTAMP WITH TIME ZONE,
    -- each change makes a new version; sent_version is the last one the integrator accepted
    version         INT                      NOT NULL DEFAULT 1,
    sent_version    INT                      NOT NULL DEFAULT 0,
    delivery        VARCHAR(10)              NOT NULL,
    provider        VARCHAR(20),
    document_number VARCHAR(40),
    attempts        INT                      NOT NULL DEFAULT 0,
    last_error      VARCHAR(255),
    next_attempt_at TIMESTAMP WITH TIME ZONE,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    lock_version    BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT uq_adisyons_bill UNIQUE (bill_id),
    CONSTRAINT uq_adisyons_ettn UNIQUE (ettn),
    CONSTRAINT ck_adisyons_status CHECK (status IN ('OPEN', 'CLOSED', 'CANCELLED')),
    CONSTRAINT ck_adisyons_delivery CHECK (delivery IN ('PENDING', 'SENT', 'FAILED'))
);
CREATE INDEX ix_adisyons_opened ON adisyons (business_id, opened_at);
CREATE INDEX ix_adisyons_delivery ON adisyons (delivery, next_attempt_at);

-- the business's own e-Adisyon integrator, beside its e-Arşiv integrator and delivery platforms
ALTER TABLE integration_settings DROP CONSTRAINT ck_integration_settings_kind;
ALTER TABLE integration_settings ADD CONSTRAINT ck_integration_settings_kind
    CHECK (kind IN ('E_ARSIV', 'E_ADISYON', 'YEMEKSEPETI', 'GETIR', 'TRENDYOL'));
