-- Chains (docs/adr/0001-multi-business.md, phase B): a business has branches; what happens in a place belongs to
-- that place. The menu, staff, stock and coupons stay with the business. Every existing business gets one branch,
-- "Merkez", and everything that exists today belongs to it.
CREATE TABLE branches
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT                   NOT NULL REFERENCES businesses (id),
    code        VARCHAR(20)              NOT NULL,
    name        VARCHAR(80)              NOT NULL,
    active      BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_branches_code UNIQUE (business_id, code)
);
CREATE INDEX ix_branches_business ON branches (business_id);

INSERT INTO branches (business_id, code, name, created_at)
SELECT id, 'merkez', 'Merkez', CURRENT_TIMESTAMP FROM businesses;

