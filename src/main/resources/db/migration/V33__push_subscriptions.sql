-- Push notifications (docs/OPERATIONS.md): a device asks to be told of new orders, ready plates or guests calling.
-- A subscription is the browser's push address and keys (Web Push, RFC 8291), or a store app's token later. It
-- belongs to the person who made it and to their branch (null: all branches).
CREATE TABLE push_subscriptions
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id     BIGINT                   NOT NULL REFERENCES businesses (id),
    branch_id       BIGINT REFERENCES branches (id),
    username        VARCHAR(50)              NOT NULL,
    kind            VARCHAR(10)              NOT NULL,
    endpoint        VARCHAR(1000)            NOT NULL UNIQUE,
    p256dh          VARCHAR(120),
    auth            VARCHAR(40),
    topics          VARCHAR(100)             NOT NULL,
    lang            VARCHAR(5)               NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    last_success_at TIMESTAMP WITH TIME ZONE,
    failures        INTEGER                  NOT NULL DEFAULT 0,
    CONSTRAINT ck_push_subscriptions_kind CHECK (kind IN ('WEB', 'FCM'))
);
CREATE INDEX ix_push_subscriptions_business ON push_subscriptions (business_id);

-- The server's own VAPID key pair (RFC 8292), made once on first use unless given in the environment. Server-wide:
-- push services know a sender by it. The private key is sealed when the server has an encryption key.
CREATE TABLE push_keys
(
    id          BIGINT                   NOT NULL PRIMARY KEY,
    public_key  VARCHAR(120)             NOT NULL,
    private_key VARCHAR(600)             NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
