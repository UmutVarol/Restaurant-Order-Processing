-- Orders from delivery platforms (Yemeksepeti, Getir Yemek, Trendyol Go).

-- which of our dishes a platform's menu item is
CREATE TABLE channel_item_mappings
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel       VARCHAR(20)  NOT NULL,
    external_id   VARCHAR(80)  NOT NULL,
    external_name VARCHAR(120) NOT NULL,
    menu_item_id  BIGINT       NOT NULL REFERENCES menu_items (id) ON DELETE CASCADE,
    CONSTRAINT uq_channel_item_mappings UNIQUE (channel, external_id)
);
CREATE INDEX ix_channel_item_mappings_item ON channel_item_mappings (menu_item_id);

-- Every order a platform sent, once: the platform's id is unique per channel, so a webhook delivered twice is
-- recognised. An order that cannot be placed safely (an item nobody mapped) waits in ATTENTION.
CREATE TABLE channel_orders
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel        VARCHAR(20)    NOT NULL,
    external_id    VARCHAR(80)    NOT NULL,
    status         VARCHAR(12)    NOT NULL,
    order_id       BIGINT REFERENCES orders (id),
    payload        TEXT           NOT NULL,
    platform_total NUMERIC(12, 2) NOT NULL,
    our_total      NUMERIC(12, 2),
    price_differs  BOOLEAN        NOT NULL DEFAULT FALSE,
    problem_code   VARCHAR(40),
    problem        VARCHAR(255),
    synced_status  VARCHAR(20),
    sync_error     VARCHAR(255),
    received_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    version        BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_channel_orders UNIQUE (channel, external_id),
    CONSTRAINT ck_channel_orders_status CHECK (status IN ('ATTENTION', 'PLACED', 'REJECTED'))
);
CREATE INDEX ix_channel_orders_order ON channel_orders (order_id);
CREATE INDEX ix_channel_orders_received ON channel_orders (received_at);

