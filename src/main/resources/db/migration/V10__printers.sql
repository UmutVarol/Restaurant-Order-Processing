-- Kitchen and bar printers on the restaurant's network, and the tickets sent to them.

CREATE TABLE printers
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(40)              NOT NULL UNIQUE,
    -- a private-network address only (checked again before every connection)
    host            VARCHAR(100)             NOT NULL,
    port            INTEGER                  NOT NULL,
    paper_width     INTEGER                  NOT NULL,
    -- which menu categories this printer gets, e.g. "STARTER,MAIN"
    categories      VARCHAR(100)             NOT NULL,
    enabled         BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    last_printed_at TIMESTAMP WITH TIME ZONE,
    last_error      VARCHAR(255),
    CONSTRAINT ck_printers_paper CHECK (paper_width IN (58, 80))
);

CREATE TABLE print_jobs
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    printer_id      BIGINT                   NOT NULL REFERENCES printers (id) ON DELETE CASCADE,
    order_id        BIGINT REFERENCES orders (id),
    kind            VARCHAR(20)              NOT NULL,
    status          VARCHAR(20)              NOT NULL,
    attempts        INTEGER                  NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_error      VARCHAR(255),
    requested_by    VARCHAR(50),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    printed_at      TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_print_jobs_kind CHECK (kind IN ('TICKET', 'REPRINT', 'TEST')),
    CONSTRAINT ck_print_jobs_status CHECK (status IN ('QUEUED', 'PRINTED', 'FAILED'))
);

CREATE INDEX ix_print_jobs_due ON print_jobs (status, next_attempt_at);
CREATE INDEX ix_print_jobs_order ON print_jobs (order_id);
