-- Staff scheduling, the time clock and tip pooling.

-- the planned rota
CREATE TABLE shifts
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL REFERENCES app_users (id),
    starts_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    note       VARCHAR(80),
    created_by VARCHAR(50)              NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_shifts_order CHECK (ends_at > starts_at)
);
CREATE INDEX ix_shifts_start ON shifts (starts_at);
CREATE INDEX ix_shifts_user ON shifts (user_id, starts_at);

-- what was actually worked
CREATE TABLE time_entries
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT                   NOT NULL REFERENCES app_users (id),
    -- the user's id while the entry is open, null once closed: unique, so nobody is clocked in twice
    open_user_id      BIGINT UNIQUE,
    clocked_in_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    clocked_out_at    TIMESTAMP WITH TIME ZONE,
    clocked_in_by     VARCHAR(50)              NOT NULL,
    clocked_out_by    VARCHAR(50),
    corrected_by      VARCHAR(50),
    correction_reason VARCHAR(140),
    version           BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT ck_time_entries_order CHECK (clocked_out_at IS NULL OR clocked_out_at > clocked_in_at),
    CONSTRAINT ck_time_entries_open CHECK ((open_user_id IS NULL) = (clocked_out_at IS NOT NULL))
);
CREATE INDEX ix_time_entries_in ON time_entries (clocked_in_at);
CREATE INDEX ix_time_entries_user ON time_entries (user_id, clocked_in_at);

-- a day's tips, shared out once and then fixed, for payroll
CREATE TABLE tip_pools
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_date DATE                     NOT NULL UNIQUE,
    tips_total    NUMERIC(12, 2)           NOT NULL,
    created_by    VARCHAR(50)              NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE tip_shares
(
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool_id BIGINT         NOT NULL REFERENCES tip_pools (id) ON DELETE CASCADE,
    user_id BIGINT         NOT NULL REFERENCES app_users (id),
    minutes INTEGER        NOT NULL,
    weight  NUMERIC(4, 2)  NOT NULL,
    amount  NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_tip_shares_amount CHECK (amount >= 0 AND minutes >= 0)
);
CREATE INDEX ix_tip_shares_user ON tip_shares (user_id);
