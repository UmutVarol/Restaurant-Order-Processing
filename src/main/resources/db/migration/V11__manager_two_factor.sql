-- Two-step sign-in for managers: a TOTP authenticator app (RFC 6238) and one-time recovery codes.

-- the shared secret, encrypted with AES-GCM under TOTP_ENCRYPTION_KEY; set but not enabled while enrolling
ALTER TABLE app_users ADD COLUMN totp_secret VARCHAR(255);
ALTER TABLE app_users ADD COLUMN totp_enabled BOOLEAN NOT NULL DEFAULT FALSE;
-- the last 30-second step a code was accepted for, so a code cannot be used twice
ALTER TABLE app_users ADD COLUMN totp_last_step BIGINT NOT NULL DEFAULT 0;

CREATE TABLE recovery_codes
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    code_hash  VARCHAR(100)             NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_recovery_codes_user ON recovery_codes (user_id);
