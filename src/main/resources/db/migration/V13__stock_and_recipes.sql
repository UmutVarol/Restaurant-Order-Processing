-- Stock and recipe costing: ingredients, recipes per dish and per option, and an append-only stock ledger.

CREATE TABLE ingredients
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(60)    NOT NULL,
    -- the base unit recipes and the ledger count in: GRAM, MILLILITRE or PIECE
    unit            VARCHAR(12)    NOT NULL,
    -- price per kilogram, litre or piece
    cost            NUMERIC(12, 2) NOT NULL,
    -- in base units; at or below it the ingredient is reported as low
    low_stock_level NUMERIC(14, 3),
    -- an untracked ingredient is costed but never sells a dish out
    track_stock     BOOLEAN        NOT NULL DEFAULT TRUE,
    archived        BOOLEAN        NOT NULL DEFAULT FALSE,
    version         BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT ck_ingredients_unit CHECK (unit IN ('GRAM', 'MILLILITRE', 'PIECE')),
    CONSTRAINT ck_ingredients_cost CHECK (cost >= 0),
    CONSTRAINT ck_ingredients_low CHECK (low_stock_level IS NULL OR low_stock_level >= 0)
);
CREATE INDEX ix_ingredients_name ON ingredients (name);

-- What a dish uses. A line with an option applies only when that choice is on the order line; it is matched by
-- group and choice name, because options are copied onto orders by name and their ids change when a menu is edited.
-- An option line can replace one of the dish's own ingredients (plain yogurt instead of garlic yogurt).
CREATE TABLE recipe_lines
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_id           BIGINT         NOT NULL REFERENCES menu_items (id) ON DELETE CASCADE,
    option_group           VARCHAR(40),
    option_choice          VARCHAR(40),
    ingredient_id          BIGINT         NOT NULL REFERENCES ingredients (id),
    quantity               NUMERIC(12, 3) NOT NULL,
    replaces_ingredient_id BIGINT REFERENCES ingredients (id),
    CONSTRAINT ck_recipe_lines_quantity CHECK (quantity >= 0),
    CONSTRAINT ck_recipe_lines_option CHECK ((option_group IS NULL AND option_choice IS NULL AND replaces_ingredient_id IS NULL)
        OR (option_group IS NOT NULL AND option_choice IS NOT NULL))
);
CREATE INDEX ix_recipe_lines_item ON recipe_lines (menu_item_id);
CREATE INDEX ix_recipe_lines_ingredient ON recipe_lines (ingredient_id);

-- The ledger. Rows are only ever inserted: the balance is the sum of an ingredient's movements, so two tills
-- recording at once can never overwrite each other. quantity is signed, in base units.
CREATE TABLE stock_movements
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id BIGINT         NOT NULL REFERENCES ingredients (id),
    kind          VARCHAR(12)    NOT NULL,
    quantity      NUMERIC(14, 3) NOT NULL,
    -- price per kilogram, litre or piece at the time: what a delivery cost, otherwise the ingredient's cost
    unit_cost     NUMERIC(12, 2) NOT NULL,
    order_id      BIGINT,
    -- one sale movement per order and ingredient, so completing an order can never deduct twice
    sale_key      VARCHAR(60) UNIQUE,
    reason        VARCHAR(200),
    supplier      VARCHAR(80),
    actor         VARCHAR(50)    NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_stock_movements_kind CHECK (kind IN ('SALE', 'WASTE', 'DELIVERY', 'COUNT'))
);
CREATE INDEX ix_stock_movements_ingredient ON stock_movements (ingredient_id, created_at);
CREATE INDEX ix_stock_movements_created ON stock_movements (created_at);

-- set by the stock ledger: a dish whose ingredient ran out cannot be ordered until it is restocked
ALTER TABLE menu_items ADD COLUMN stock_out BOOLEAN NOT NULL DEFAULT FALSE;
