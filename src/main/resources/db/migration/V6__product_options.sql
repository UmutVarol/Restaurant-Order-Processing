-- Product options (modifiers): groups of choices per dish, and the choices copied onto order lines.
-- Portable across PostgreSQL and H2.

CREATE TABLE option_groups
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_id BIGINT      NOT NULL REFERENCES menu_items (id) ON DELETE CASCADE,
    name         VARCHAR(60) NOT NULL,
    min_select   INTEGER     NOT NULL,
    max_select   INTEGER     NOT NULL,
    sort_order   INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT ck_option_groups_limits CHECK (min_select >= 0 AND max_select >= 1 AND min_select <= max_select)
);

CREATE INDEX ix_option_groups_item ON option_groups (menu_item_id);

CREATE TABLE option_choices
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id    BIGINT         NOT NULL REFERENCES option_groups (id) ON DELETE CASCADE,
    name        VARCHAR(60)    NOT NULL,
    price_delta NUMERIC(12, 2) NOT NULL DEFAULT 0,
    sort_order  INTEGER        NOT NULL DEFAULT 0,
    CONSTRAINT ck_option_choices_price CHECK (price_delta >= 0)
);

CREATE INDEX ix_option_choices_group ON option_choices (group_id);

-- No foreign key to option_choices: menus change, but what was ordered must stay on the order.
CREATE TABLE order_line_options
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_line_id BIGINT         NOT NULL REFERENCES order_lines (id) ON DELETE CASCADE,
    choice_id     BIGINT,
    group_name    VARCHAR(60)    NOT NULL,
    choice_name   VARCHAR(60)    NOT NULL,
    price_delta   NUMERIC(12, 2) NOT NULL
);

CREATE INDEX ix_order_line_options_line ON order_line_options (order_line_id);

