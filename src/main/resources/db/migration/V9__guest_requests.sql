-- Ordering from the table by QR code, calling the waiter and asking for the bill.

-- each table's QR code carries a random token; only its SHA-256 is stored, and a manager can replace it at any time
ALTER TABLE dining_tables ADD COLUMN qr_token_hash VARCHAR(64);
ALTER TABLE dining_tables ADD COLUMN qr_issued_at TIMESTAMP WITH TIME ZONE;
CREATE UNIQUE INDEX ux_dining_tables_qr_token_hash ON dining_tables (qr_token_hash);

-- what guests ask for; an order only reaches the kitchen once a waiter accepts it
CREATE TABLE guest_requests
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- what the guest's phone knows the request by: random, so requests cannot be enumerated
    public_id    VARCHAR(36)              NOT NULL UNIQUE,
    table_id     BIGINT                   NOT NULL REFERENCES dining_tables (id),
    kind         VARCHAR(20)              NOT NULL,
    status       VARCHAR(20)              NOT NULL,
    guest_name   VARCHAR(40),
    note         VARCHAR(140),
    quoted_total NUMERIC(12, 2),
    order_id     BIGINT REFERENCES orders (id),
    reason       VARCHAR(140),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    handled_at   TIMESTAMP WITH TIME ZONE,
    handled_by   VARCHAR(50),
    version      BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT ck_guest_requests_kind CHECK (kind IN ('ORDER', 'CALL_WAITER', 'REQUEST_BILL')),
    CONSTRAINT ck_guest_requests_status CHECK (status IN ('OPEN', 'ACCEPTED', 'REJECTED', 'DONE'))
);

CREATE INDEX ix_guest_requests_status ON guest_requests (status, created_at);
CREATE INDEX ix_guest_requests_table ON guest_requests (table_id, created_at);

CREATE TABLE guest_request_lines
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id   BIGINT         NOT NULL REFERENCES guest_requests (id) ON DELETE CASCADE,
    menu_item_id BIGINT         NOT NULL,
    item_name    VARCHAR(80)    NOT NULL,
    item_icon    VARCHAR(16),
    quantity     INTEGER        NOT NULL,
    note         VARCHAR(140),
    option_ids   VARCHAR(200),
    options_text VARCHAR(255),
    line_total   NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_guest_request_lines_quantity CHECK (quantity BETWEEN 1 AND 20)
);

CREATE INDEX ix_guest_request_lines_request ON guest_request_lines (request_id);
