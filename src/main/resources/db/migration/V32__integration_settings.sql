-- Each business connects its own e-Arşiv integrator and delivery platforms (Sofra Cloud): one row per business and
-- kind. Keys and webhook secrets are sealed with AES-GCM like the payment keys (V28); only their last characters are
-- kept readable. A restaurant's own server can still use the server-wide settings from its environment.
CREATE TABLE integration_settings
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id    BIGINT                   NOT NULL REFERENCES businesses (id),
    kind           VARCHAR(20)              NOT NULL,
    base_url       VARCHAR(255),
    api_key        VARCHAR(600),
    webhook_secret VARCHAR(600),
    key_hint       VARCHAR(8),
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by     VARCHAR(50)              NOT NULL,
    version        BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT uq_integration_settings UNIQUE (business_id, kind),
    CONSTRAINT ck_integration_settings_kind CHECK (kind IN ('E_ARSIV', 'YEMEKSEPETI', 'GETIR', 'TRENDYOL'))
);
