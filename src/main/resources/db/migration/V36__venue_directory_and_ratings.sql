-- Round three: Sofra as a place guests and restaurants share.
-- A branch can appear in the guest app's directory: where it is, and whether it wants to be found at all.
ALTER TABLE branches ADD COLUMN latitude DOUBLE PRECISION;
ALTER TABLE branches ADD COLUMN longitude DOUBLE PRECISION;
ALTER TABLE branches ADD COLUMN address VARCHAR(200);
ALTER TABLE branches ADD COLUMN listed BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE branches ADD CONSTRAINT ck_branches_position
    CHECK ((latitude IS NULL AND longitude IS NULL)
        OR (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180));
CREATE INDEX ix_branches_listed_position ON branches (listed, latitude, longitude);

-- A guest saying "I am here": which branch, how they found it, and an anonymous device key (a hash, never the
-- device's own id) so a returning guest can be counted without knowing who they are.
CREATE TABLE venue_checkins
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT                   NOT NULL REFERENCES businesses (id),
    branch_id   BIGINT                   NOT NULL REFERENCES branches (id),
    device_hash VARCHAR(64)              NOT NULL,
    method      VARCHAR(10)              NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_venue_checkins_method CHECK (method IN ('NEARBY', 'LIST', 'QR', 'NFC', 'LINK'))
);
CREATE INDEX ix_venue_checkins_branch_time ON venue_checkins (branch_id, created_at);
CREATE INDEX ix_venue_checkins_device ON venue_checkins (business_id, device_hash, created_at);

-- A verified visit's rating: only a bill that was paid can be rated, once. The restaurant may answer it in public.
CREATE TABLE visit_ratings
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT                   NOT NULL REFERENCES businesses (id),
    branch_id   BIGINT                   NOT NULL REFERENCES branches (id),
    bill_id     BIGINT                   NOT NULL UNIQUE REFERENCES bills (id),
    stars       SMALLINT                 NOT NULL,
    tags        VARCHAR(200),
    liked       VARCHAR(400),
    comment     VARCHAR(500),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    reply       VARCHAR(500),
    replied_at  TIMESTAMP WITH TIME ZONE,
    replied_by  VARCHAR(50),
    CONSTRAINT ck_visit_ratings_stars CHECK (stars BETWEEN 1 AND 5)
);
CREATE INDEX ix_visit_ratings_branch_time ON visit_ratings (branch_id, created_at);
