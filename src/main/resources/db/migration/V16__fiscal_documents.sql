-- The legal document for each bill: a receipt from the yeni nesil ÖKC at the till, or an e-Arşiv invoice through a
-- GİB-authorised integrator. One per bill at most (the bill id is unique), never changed once issued.
CREATE TABLE fiscal_documents
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id         BIGINT         NOT NULL UNIQUE REFERENCES bills (id),
    kind            VARCHAR(10)    NOT NULL,
    -- WAITING: a guest asked for an invoice and the bill is still open; PENDING and FAILED are retried
    status          VARCHAR(10)    NOT NULL,
    provider        VARCHAR(20),
    reference       VARCHAR(80),
    document_number VARCHAR(40),
    pdf_url         VARCHAR(255),
    total           NUMERIC(12, 2),
    tax             NUMERIC(12, 2),
    buyer_name      VARCHAR(120),
    -- the guest's VKN (10 digits) or TCKN (11 digits); printed on the invoice, never written to logs
    buyer_tax_id    VARCHAR(11),
    buyer_address   VARCHAR(255),
    attempts        INTEGER        NOT NULL DEFAULT 0,
    last_error      VARCHAR(255),
    next_attempt_at TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    issued_at       TIMESTAMP WITH TIME ZONE,
    version         BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT ck_fiscal_documents_kind CHECK (kind IN ('RECEIPT', 'E_ARSIV')),
    CONSTRAINT ck_fiscal_documents_status CHECK (status IN ('WAITING', 'PENDING', 'ISSUED', 'FAILED'))
);
CREATE INDEX ix_fiscal_documents_due ON fiscal_documents (status, next_attempt_at);
CREATE INDEX ix_fiscal_documents_issued ON fiscal_documents (issued_at);
