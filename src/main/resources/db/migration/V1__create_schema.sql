-- Sofra schema. Portable across PostgreSQL and H2.

CREATE TABLE app_users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(80)  NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_app_users_role CHECK (role IN ('ADMIN', 'WAITER', 'KITCHEN'))
);

CREATE TABLE menu_items
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(80)    NOT NULL UNIQUE,
    description       VARCHAR(255),
    category          VARCHAR(20)    NOT NULL,
    price             NUMERIC(12, 2) NOT NULL,
    icon              VARCHAR(16),
    prep_time_minutes INTEGER        NOT NULL DEFAULT 0,
    popular           BOOLEAN        NOT NULL DEFAULT FALSE,
    available         BOOLEAN        NOT NULL DEFAULT TRUE,
    archived          BOOLEAN        NOT NULL DEFAULT FALSE,
    version           BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT ck_menu_items_price CHECK (price > 0),
    CONSTRAINT ck_menu_items_category CHECK (category IN ('STARTER', 'MAIN', 'DESSERT', 'DRINK'))
);

CREATE TABLE menu_item_tags
(
    menu_item_id BIGINT      NOT NULL REFERENCES menu_items (id) ON DELETE CASCADE,
    tag          VARCHAR(20) NOT NULL,
    PRIMARY KEY (menu_item_id, tag),
    CONSTRAINT ck_menu_item_tags_tag CHECK (tag IN ('VEGETARIAN', 'VEGAN', 'GLUTEN_FREE', 'SPICY'))
);

CREATE TABLE dining_tables
(
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code  VARCHAR(10) NOT NULL UNIQUE,
    seats INTEGER     NOT NULL,
    zone  VARCHAR(20) NOT NULL,
    CONSTRAINT ck_dining_tables_seats CHECK (seats > 0)
);

CREATE TABLE coupons
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(32)    NOT NULL UNIQUE,
    description      VARCHAR(120)   NOT NULL,
    discount_type    VARCHAR(20)    NOT NULL,
    discount_value   NUMERIC(12, 2) NOT NULL,
    minimum_subtotal NUMERIC(12, 2) NOT NULL DEFAULT 0,
    max_discount     NUMERIC(12, 2),
    active           BOOLEAN        NOT NULL DEFAULT TRUE,
    valid_until      TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_coupons_value CHECK (discount_value > 0),
    CONSTRAINT ck_coupons_percentage CHECK (discount_type <> 'PERCENTAGE' OR discount_value <= 100)
);

CREATE TABLE orders
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    type                VARCHAR(20)              NOT NULL,
    status              VARCHAR(20)              NOT NULL,
    customer_name       VARCHAR(80)              NOT NULL,
    customer_phone      VARCHAR(20),
    table_id            BIGINT REFERENCES dining_tables (id),
    delivery_address    VARCHAR(255),
    note                VARCHAR(255),
    payment_method      VARCHAR(20)              NOT NULL,
    coupon_code         VARCHAR(32),
    subtotal            NUMERIC(12, 2)           NOT NULL,
    discount            NUMERIC(12, 2)           NOT NULL,
    tax                 NUMERIC(12, 2)           NOT NULL,
    delivery_fee        NUMERIC(12, 2)           NOT NULL,
    total               NUMERIC(12, 2)           NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by          VARCHAR(50),
    cancellation_reason VARCHAR(255),
    version             BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT ck_orders_type CHECK (type IN ('DINE_IN', 'TAKEAWAY', 'DELIVERY')),
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING', 'PREPARING', 'READY', 'SERVED', 'OUT_FOR_DELIVERY', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_orders_payment CHECK (payment_method IN ('CASH', 'CARD', 'ONLINE')),
    CONSTRAINT ck_orders_dine_in_table CHECK (type <> 'DINE_IN' OR table_id IS NOT NULL),
    CONSTRAINT ck_orders_delivery_address CHECK (type <> 'DELIVERY' OR delivery_address IS NOT NULL),
    CONSTRAINT ck_orders_amounts CHECK (subtotal >= 0 AND discount >= 0 AND tax >= 0 AND delivery_fee >= 0 AND total >= 0)
);

CREATE INDEX ix_orders_status ON orders (status);
CREATE INDEX ix_orders_created_at ON orders (created_at);
CREATE INDEX ix_orders_table_id ON orders (table_id);

CREATE TABLE order_lines
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    menu_item_id BIGINT         NOT NULL REFERENCES menu_items (id),
    item_name    VARCHAR(80)    NOT NULL,
    item_icon    VARCHAR(16),
    category     VARCHAR(20)    NOT NULL,
    unit_price   NUMERIC(12, 2) NOT NULL,
    quantity     INTEGER        NOT NULL,
    note         VARCHAR(140),
    line_total   NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_order_lines_quantity CHECK (quantity > 0)
);

CREATE INDEX ix_order_lines_order_id ON order_lines (order_id);

CREATE TABLE order_status_history
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT                   NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    status     VARCHAR(20)              NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    changed_by VARCHAR(50)
);

CREATE INDEX ix_order_status_history_order_id ON order_status_history (order_id);
