package db.migration;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import org.flywaydb.core.api.migration.BaseJavaMigration;
import org.flywaydb.core.api.migration.Context;

/**
 * Many businesses on one Sofra (docs/adr/0001-multi-business.md): a {@code businesses} table, a {@code business_id}
 * on every business-owned table, and uniqueness that holds per business instead of across all of them.
 * Everything that exists today becomes business 1, so a single-restaurant installation carries on unchanged.
 * <p>
 * Written in Java because unique constraints declared inline have generated names that differ between PostgreSQL
 * and H2; they are found by their columns in the information schema, which both databases provide.
 */
public class V24__MultiBusiness extends BaseJavaMigration {

    /** Every table holding a business's own data (join and element-collection tables follow their owner). */
    static final List<String> TABLES = List.of(
            "app_users", "bills", "channel_item_mappings", "channel_orders", "coupons", "day_closings", "dining_tables",
            "fiscal_documents", "guest_request_lines", "guest_requests", "ingredients", "menu_items", "option_choices",
            "option_groups", "order_adjustments", "order_line_options", "order_lines", "order_status_history", "orders",
            "payment_links", "payments", "pos_devices", "print_jobs", "printers", "recipe_lines", "recovery_codes",
            "refunds", "reservations", "service_settings", "shifts", "stations", "stock_movements", "time_entries",
            "tip_pools", "tip_shares");

    /** Unique per business from now on: table → the columns that were unique on their own. */
    static final Map<String, List<List<String>>> PER_BUSINESS = new LinkedHashMap<>();

    static {
        PER_BUSINESS.put("app_users", List.of(List.of("username")));
        PER_BUSINESS.put("menu_items", List.of(List.of("name")));
        PER_BUSINESS.put("dining_tables", List.of(List.of("code")));
        PER_BUSINESS.put("coupons", List.of(List.of("code")));
        PER_BUSINESS.put("printers", List.of(List.of("name")));
        PER_BUSINESS.put("stations", List.of(List.of("code"), List.of("name")));
        PER_BUSINESS.put("tip_pools", List.of(List.of("business_date")));
        PER_BUSINESS.put("day_closings", List.of(List.of("business_date")));
        PER_BUSINESS.put("channel_item_mappings", List.of(List.of("channel", "external_id")));
        PER_BUSINESS.put("channel_orders", List.of(List.of("channel", "external_id")));
    }

    /** The busiest tables are read by business and time; the rest by business alone. */
    static final List<String> INDEXED = List.of("orders", "order_lines", "bills", "payments", "guest_requests",
            "print_jobs", "stock_movements", "reservations", "time_entries", "fiscal_documents", "app_users",
            "menu_items", "dining_tables");

    @Override
    public void migrate(Context context) throws Exception {
        Connection connection = context.getConnection();
        try (Statement sql = connection.createStatement()) {
            sql.execute("""
                    CREATE TABLE businesses
                    (
                        id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        slug          VARCHAR(40)              NOT NULL UNIQUE,
                        name          VARCHAR(80)              NOT NULL,
                        time_zone     VARCHAR(40)              NOT NULL,
                        plan          VARCHAR(20)              NOT NULL,
                        status        VARCHAR(20)              NOT NULL,
                        trial_ends_at TIMESTAMP WITH TIME ZONE,
                        created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
                        CONSTRAINT ck_businesses_plan CHECK (plan IN ('STARTER', 'BUSINESS', 'CHAIN')),
                        CONSTRAINT ck_businesses_status CHECK (status IN ('TRIAL', 'ACTIVE', 'PAST_DUE', 'READ_ONLY', 'CANCELLED'))
                    )""");
            // an installation that already has data is its own, paying-for-itself business: nothing to bill
            sql.execute("""
                    INSERT INTO businesses (id, slug, name, time_zone, plan, status, created_at)
                    VALUES (1, 'default', 'Sofra', 'Europe/Istanbul', 'BUSINESS', 'ACTIVE', CURRENT_TIMESTAMP)""");
            // the identity must continue after the row inserted with an explicit id
            restartIdentity(connection, sql);

            for (String table : TABLES) {
                sql.execute("ALTER TABLE " + table + " ADD COLUMN business_id BIGINT DEFAULT 1 NOT NULL");
                sql.execute("ALTER TABLE " + table + " ALTER COLUMN business_id DROP DEFAULT");
                sql.execute("ALTER TABLE " + table + " ADD CONSTRAINT fk_" + table + "_business FOREIGN KEY (business_id) REFERENCES businesses (id)");
            }
            // a dish's kitchen station is referenced by code: it now has to be a station of the same business
            for (String constraint : constraints(connection, "menu_items", "FOREIGN KEY", List.of("station_code"))) {
                sql.execute("ALTER TABLE menu_items DROP CONSTRAINT " + constraint);
            }
            for (Map.Entry<String, List<List<String>>> entry : PER_BUSINESS.entrySet()) {
                String table = entry.getKey();
                for (List<String> columns : entry.getValue()) {
                    for (String constraint : uniqueConstraints(connection, table, columns)) {
                        sql.execute("ALTER TABLE " + table + " DROP CONSTRAINT " + constraint);
                    }
                    sql.execute("ALTER TABLE " + table + " ADD CONSTRAINT uq_" + table + "_" + String.join("_", columns)
                            + "_per_business UNIQUE (business_id, " + String.join(", ", columns) + ")");
                }
            }
            sql.execute("""
                    ALTER TABLE menu_items ADD CONSTRAINT fk_menu_items_station
                    FOREIGN KEY (business_id, station_code) REFERENCES stations (business_id, code)""");
            for (String table : INDEXED) {
                sql.execute("CREATE INDEX ix_" + table + "_business ON " + table + " (business_id)");
            }
        }
    }

    /** The unique constraints of {@code table} covering exactly {@code columns}, whatever they are called. */
    private static List<String> uniqueConstraints(Connection connection, String table, List<String> columns) throws Exception {
        List<String> found = constraints(connection, table, "UNIQUE", columns);
        if (found.isEmpty()) {
            throw new IllegalStateException("No unique constraint on " + table + " " + columns);
        }
        return found;
    }

    /** Constraints of a type on {@code table} covering exactly {@code columns}, whatever they are called. */
    private static List<String> constraints(Connection connection, String table, String type, List<String> columns) throws Exception {
        Map<String, Set<String>> byConstraint = new LinkedHashMap<>();
        try (PreparedStatement query = connection.prepareStatement("""
                SELECT tc.constraint_name, k.column_name
                FROM information_schema.table_constraints tc
                JOIN information_schema.key_column_usage k
                  ON k.constraint_name = tc.constraint_name AND k.table_name = tc.table_name
                 AND k.constraint_schema = tc.constraint_schema
                WHERE lower(tc.table_name) = ? AND tc.constraint_type = ?
                  AND tc.constraint_schema = ?""")) {
            query.setString(1, table);
            query.setString(2, type);
            query.setString(3, connection.getSchema());
            try (ResultSet rows = query.executeQuery()) {
                while (rows.next()) {
                    byConstraint.computeIfAbsent(rows.getString(1), key -> new TreeSet<>())
                            .add(rows.getString(2).toLowerCase(Locale.ROOT));
                }
            }
        }
        Set<String> wanted = new TreeSet<>(columns);
        List<String> found = new ArrayList<>();
        byConstraint.forEach((name, cols) -> {
            if (cols.equals(wanted)) {
                found.add(name);
            }
        });
        return found;
    }

    private static void restartIdentity(Connection connection, Statement sql) throws Exception {
        String product = connection.getMetaData().getDatabaseProductName().toLowerCase(Locale.ROOT);
        if (product.contains("postgres")) {
            sql.execute("SELECT setval(pg_get_serial_sequence('businesses', 'id'), 1)");
        } else {
            sql.execute("ALTER TABLE businesses ALTER COLUMN id RESTART WITH 2");
        }
    }
}
